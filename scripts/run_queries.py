"""
Paso 7 - Ejecuta las 12 consultas con sus parámetros por defecto y genera
docs/queries_results.md con el formato que pide el enunciado:
pregunta, SQL, muestra del resultado y por qué es relevante (+ autor).
"""
import time

from db import ROOT, get_connection
from query_lib import load_queries, run_query, run_transaction_query

OUT = ROOT / "docs" / "queries_results.md"
SAMPLE = 10


def md_table(cols, rows) -> list[str]:
    def f(v):
        return "NULL" if v is None else str(v).replace("|", "\\|").replace("\n", " ")[:60]
    return ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + \
           ["| " + " | ".join(f(v) for v in r) + " |" for r in rows[:SAMPLE]]


def main() -> None:
    conn = get_connection()
    lines = ["# SQL queries", "",
             "_Generated by `scripts/run_queries.py` with each query's default parameters. "
             f"Only the first {SAMPLE} rows of each result are shown._", "",
             "| ID | Title | Author | Techniques |", "|---|---|---|---|"]
    queries = load_queries()
    lines += [f"| {q['id']} | {q['title']} | {q['author']} | {q['techniques']} |" for q in queries.values()]
    lines.append("")
    for q in queries.values():
        t0 = time.time()
        if q.get("type") == "transaction":
            cols, rows, updated = run_transaction_query(conn, q)
            extra = f"\n_UPDATE affected {updated} rows; the transaction then ended with ROLLBACK._\n"
        else:
            cols, rows = run_query(conn, q)
            extra = f"\n_{len(rows)} rows returned._\n"
        ms = (time.time() - t0) * 1000
        lines += [f"## {q['id']} - {q['title']}", "",
                  f"**Author:** {q['author']}  ", f"**Question:** {q['question']}  ",
                  f"**Techniques:** {q['techniques']}  ", f"**Default parameters:** `{q['params']}`", "",
                  "```sql", q["sql"], "```", "", "**Sample result:**", ""]
        lines += md_table(cols, rows)
        lines += [extra, f"**Why it is meaningful:** {q['why']}", "", f"_Execution time: {ms:.0f} ms_", ""]
        print(f"  {q['id']}  {len(rows):>4} filas  {ms:7.0f} ms  {q['title']}")
    conn.close()
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Escrito {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
