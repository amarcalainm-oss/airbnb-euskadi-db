import re
from datetime import datetime

from db import ROOT, SQL_DIR, get_connection

OUT = ROOT / "docs" / "profiling_results.md"
MAX_ROWS = 60


def split_queries(text: str) -> list[tuple[str, str]]:
    """(title, sql) blocks that start with '-- @query <title>'."""
    parts = re.split(r"^-- @query (.+)$", text, flags=re.M)
    return [(parts[i].strip(), parts[i + 1].strip()) for i in range(1, len(parts), 2)]


def md_cell(v) -> str:
    if v is None:
        return "NULL"
    return str(v).replace("|", "\\|").replace("\n", " ")


def main() -> None:
    conn = get_connection()
    lines = [
        "# Profiling of the raw data",
        "",
        f"_Generated by `scripts/run_profiling.py` on {datetime.now():%Y-%m-%d %H:%M}._",
        "_Each table is the literal result of a SQL query on the `staging` schema._",
        "",
    ]
    for path in sorted((SQL_DIR / "profiling").glob("*.sql")):
        lines += [f"## {path.stem}", "", f"File: `sql/profiling/{path.name}`", ""]
        for title, query in split_queries(path.read_text(encoding="utf-8")):
            with conn.cursor() as cur:
                cur.execute(query)
                cols = [d.name for d in cur.description]
                rows = cur.fetchmany(MAX_ROWS)
            lines += [f"### {title}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
            lines += ["| " + " | ".join(md_cell(v) for v in r) + " |" for r in rows]
            lines.append("")
            print(f"  ok  {path.name}: {title}")
    conn.rollback()
    conn.close()
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Results written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
